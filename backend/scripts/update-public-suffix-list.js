#!/usr/bin/env node
'use strict';
/**
 * Regenerate the Public Suffix List the mail-server plugin vendors as data
 * (marketplace/plugins/mail-server/lib/public-suffix-list.js), used to find the organizational domain
 * for DMARC alignment (RFC 7489 §3.2).
 *
 *   node backend/scripts/update-public-suffix-list.js            # download from publicsuffix.org
 *   node backend/scripts/update-public-suffix-list.js list.dat   # or convert a local copy
 *
 * The plugin cannot fetch the list at runtime (it runs in the plugin sandbox and must work offline),
 * so the list ships as a plain module. Internationalized rules are stored in their ASCII (punycode)
 * form, which is how domains appear in SMTP, DKIM d= and DNS.
 */
const fs = require('fs');
const path = require('path');
const url = require('url');

const SOURCE_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = path.resolve(__dirname, '../../marketplace/plugins/mail-server/lib/public-suffix-list.js');

async function readList(arg) {
    if (arg) return fs.readFileSync(arg, 'utf8');
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`${SOURCE_URL}: HTTP ${res.status}`);
    return await res.text();
}

function convert(text) {
    const version = (/^\/\/ VERSION: (\S+)/m.exec(text) || [])[1] || 'unknown';
    const commit = (/^\/\/ COMMIT: (\S+)/m.exec(text) || [])[1] || '';
    const rules = new Set();
    for (const rawLine of text.split(/\r?\n/)) {
        const line = rawLine.trim().split(/\s/)[0];
        if (!line || line.startsWith('//')) continue;
        const prefix = line.startsWith('!') ? '!' : '';
        const body = prefix ? line.slice(1) : line;
        const labels = body.split('.').map((l) => (l === '*' ? '*' : url.domainToASCII(l) || ''));
        if (labels.some((l) => !l)) throw new Error(`unconvertible rule: ${line}`);
        rules.add(prefix + labels.join('.').toLowerCase());
    }
    if (rules.size < 5000) throw new Error(`only ${rules.size} rules — refusing to write a truncated list`);
    return { version, commit, rules: [...rules].sort() };
}

async function main() {
    const { version, commit, rules } = convert(await readList(process.argv[2]));
    const out = `'use strict';
// GENERATED by backend/scripts/update-public-suffix-list.js — do not edit by hand.
//
// The Public Suffix List (https://publicsuffix.org/), version ${version}${commit ? ` (commit ${commit})` : ''}.
// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of
// the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.
//
// One rule per line, ICANN and private sections together, internationalized labels in punycode.
module.exports = {
    version: ${JSON.stringify(version)},
    rules: ${JSON.stringify(rules.join('\n'))},
};
`;
    fs.writeFileSync(OUT, out);
    console.log(`Wrote ${rules.length} rules (version ${version}) to ${path.relative(process.cwd(), OUT)}`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
