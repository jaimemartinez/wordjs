const TABLES = { en, es };

export function translate(lang, key, vars) {
    const table = TABLES[lang] || en;
    let s = table[key] ?? en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
}

/**
 * The text to show for an API error, in the interface language: by the server's `code` when it sends
 * one, else by the few untagged messages users actually meet, else the server's own text.
 */
export function errorText(e, t) {
    if (!e) return t('common.error');
    if (typeof e === 'string') return e;
    if (e.code && t('err.' + e.code) !== 'err.' + e.code) return t('err.' + e.code);
    const msg = String(e.message || '');
    let m;
    if ((m = /^Invalid recipient email address format: (.+)$/.exec(msg))) return t('err.invalidRecipient', { addr: m[1] });
    if (/rate limit exceeded/i.test(msg)) return t('err.rateLimit');
    if (/^Too many recipients/i.test(msg)) return t('err.tooMany');
    if (/^Missing (recipient|required fields)/i.test(msg)) return t('err.missingRecipient');
    return msg || t('common.error');
}

/** The current admin language and a `t(key, vars)` bound to it. */
export function useT() {
    const ctx = useOptionalI18n ? useOptionalI18n() : null;
    let lang = ctx?.language;
    if (!lang && typeof document !== 'undefined') lang = (document.documentElement.lang || '').slice(0, 2);
    if (lang !== 'en' && lang !== 'es') lang = 'es';
    const t = (key, vars) => translate(lang, key, vars);
    return { t, lang, locale: lang === 'es' ? 'es-ES' : 'en-US' };
}
