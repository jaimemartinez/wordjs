/**
 * Get translation for a key
 */
export function t(key: string, lang: string = 'es'): string {
    // 1. Try requested language
    if (translations[lang as Language] && translations[lang as Language][key]) {
        return translations[lang as Language][key];
    }

    // 2. Fallback to first available language (as per user request)
    const availableLangs = Object.keys(translations) as Language[];
    if (availableLangs.length > 0) {
        const firstLang = availableLangs[0];
        if (translations[firstLang][key]) {
            return translations[firstLang][key];
        }
    }

    // 3. No translation found, return key (as per user request "si no hay idiomas no se traduce")
    return key;
}

/**
 * Get language from localStorage (Global App Language)
 */
export function getStoredLanguage(): Language {
    if (typeof window === 'undefined') return 'es';
    // Use the global app key 'wordjs-lang' instead of plugin specific one
    const stored = localStorage.getItem('wordjs-lang');

    // Return stored language if it exists, otherwise default to 'es'
    // Note: We return it even if not supported, t() will handle the fallback
    return (stored as Language) || 'es';
}

/**
 * Store language preference - Deprecated for plugin, should use global app switcher
 */
export function setStoredLanguage(lang: Language): void {
    if (typeof window !== 'undefined') {
        localStorage.setItem('wordjs-lang', lang);
    }
}

