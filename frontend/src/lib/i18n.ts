/**
 * Get translation for a key
 */
export function t(key: string, lang: Language = 'es'): string {
    return translations[lang][key] || translations['en'][key] || key;
}

/**
 * Register new translations (used by plugins)
 */
export function registerTranslations(newTranslations: Record<string, Record<string, string>>) {
    Object.keys(newTranslations).forEach((lang) => {
        // Ensure the language exists in our global map (fallback to empty object if not, though we stick to supported langs)
        if (translations[lang as Language]) {
            Object.assign(translations[lang as Language], newTranslations[lang]);
        }
    });
}

/**
 * Get language from localStorage; with no choice stored, the site's own language; else Spanish.
 * Never throws and never returns a language without translations: the root-mounted host dialog
 * (contexts/ModalContext.tsx) reads it outside any I18nProvider, where a blocked storage or a
 * stale value such as 'fr' would otherwise crash t() for every confirm() on the site.
 *
 * The site's language is `<html lang>`, which app/layout.tsx renders from the site's locale option
 * (lib/documentLanguage.ts). Before it was consulted, an admin who never opened the language menu got
 * Spanish screens on an English site, mixed with the screens whose copy is still English-only.
 */
export function getStoredLanguage(): Language {
    if (typeof window === 'undefined') return 'es';
    const supported = (v: string | null | undefined): Language | null => {
        const base = (v ?? '').toLowerCase().split(/[-_]/)[0];
        return base && Object.prototype.hasOwnProperty.call(translations, base) ? (base as Language) : null;
    };
    let stored: string | null = null;
    try {
        stored = localStorage.getItem('wordjs-lang');
    } catch {
        // Storage blocked (sandboxed frame, privacy mode): fall back to the default.
    }
    if (stored && Object.prototype.hasOwnProperty.call(translations, stored)) return stored as Language;
    let siteLanguage: string | null = null;
    try {
        siteLanguage = document.documentElement.getAttribute('lang');
    } catch {
        // No document (worker-like context): fall back to the default.
    }
    return supported(siteLanguage) ?? 'es';
}

/**
 * Store language preference
 */
export function setStoredLanguage(lang: Language): void {
    if (typeof window !== 'undefined') {
        localStorage.setItem('wordjs-lang', lang);
    }
}
